Write-Host "Loading JSON data..." -ForegroundColor Cyan
$jsonContent = Get-Content -Path "geo_units_sorted_by_region_city_district.json" -Raw -Encoding UTF8
$data = $jsonContent | ConvertFrom-Json

Write-Host "Processing $($data.Count) entries..." -ForegroundColor Cyan

$entriesUpdated = 0
$missingCities = @()
$missingRegions = @()

foreach ($entry in $data) {
    $cityAr = $entry.city_name_ar
    $regionAr = $entry.region_name_ar
    
    # Add city English name
    if ($cityTranslations.ContainsKey($cityAr)) {
        $entry | Add-Member -MemberType NoteProperty -Name "city_name_en" -Value $cityTranslations[$cityAr] -Force
    } else {
        $entry | Add-Member -MemberType NoteProperty -Name "city_name_en" -Value $cityAr -Force
        if ($cityAr -notin $missingCities) {
            $missingCities += $cityAr
        }
    }
    
    # Add region English name
    if ($regionTranslations.ContainsKey($regionAr)) {
        $entry | Add-Member -MemberType NoteProperty -Name "region_name_en" -Value $regionTranslations[$regionAr] -Force
    } else {
        $entry | Add-Member -MemberType NoteProperty -Name "region_name_en" -Value $regionAr -Force
        if ($regionAr -notin $missingRegions) {
            $missingRegions += $regionAr
        }
    }
    
    $entriesUpdated++
}

Write-Host "Saving updated data..." -ForegroundColor Cyan
$data | ConvertTo-Json -Depth 10 | Set-Content -Path "geo_units_sorted_by_region_city_district.json" -Encoding UTF8

Write-Host "`n✓ Successfully updated $entriesUpdated entries!" -ForegroundColor Green

if ($missingCities.Count -gt 0) {
    Write-Host "`n⚠ Warning: $($missingCities.Count) cities not found in translation mapping:" -ForegroundColor Yellow
    foreach ($city in ($missingCities | Sort-Object)) {
        Write-Host "  - $city" -ForegroundColor Yellow
    }
}

if ($missingRegions.Count -gt 0) {
    Write-Host "`n⚠ Warning: $($missingRegions.Count) regions not found in translation mapping:" -ForegroundColor Yellow
    foreach ($region in ($missingRegions | Sort-Object)) {
        Write-Host "  - $region" -ForegroundColor Yellow
    }
}

Write-Host "`nOutput saved to: geo_units_sorted_by_region_city_district.json" -ForegroundColor Green
